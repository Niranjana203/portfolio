const menuButton = document.querySelector('.menu-toggle');
const nav = document.querySelector('.nav-links');

menuButton?.addEventListener('click', () => {
  const isOpen = nav.classList.toggle('open');
  menuButton.setAttribute('aria-expanded', String(isOpen));
  menuButton.setAttribute('aria-label', isOpen ? 'Close navigation' : 'Open navigation');
});

nav?.querySelectorAll('a').forEach(link => {
  link.addEventListener('click', () => {
    nav.classList.remove('open');
    menuButton?.setAttribute('aria-expanded', 'false');
  });
});

const revealItems = document.querySelectorAll('.reveal');
if ('IntersectionObserver' in window) {
  const observer = new IntersectionObserver((entries, obs) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('visible');
        obs.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12 });
  revealItems.forEach(item => observer.observe(item));
} else {
  revealItems.forEach(item => item.classList.add('visible'));
}

document.getElementById('year').textContent = new Date().getFullYear();

// Project enquiry links can prefill the visitor's email subject.
document.querySelectorAll('[data-project]').forEach(link => {
  link.addEventListener('click', () => {
    const project = link.getAttribute('data-project');
    const emailLink = document.querySelector('.contact-actions a[href^="mailto:"]');
    if (emailLink && project) {
      emailLink.href = `mailto:YOUR_EMAIL@example.com?subject=${encodeURIComponent('Enquiry about ' + project)}`;
    }
  });
});
